// sourceNotes says, for the sources this bench imports, what their cases are.
// Each note must agree with the importer of that source.
var sourceNotes = map[string]string{
	"baseline": `The project's own corpus (testdata/corpus), written by the people who wrote the
rules, so it says nothing independent. A case that only it provides is in neither
the development nor the held-out set, and so not in the headline.`,
	"crs": `OWASP Core Rule Set regression tests. "attack" is a test that requires the rule
set to log at least one rule ID, whatever paranoia level (1 to 4) that rule belongs
to: the importer does not filter by level, and protocol checks are included
(category protocol; a missing Accept header is one example). "near-miss" is a test
that only forbids rule IDs. The CRS rates therefore ask for more than a
paranoia-level-1 view would, which this bench does not compute. Which part of a
request is its payload is decided by a heuristic; a case where it names none is
split by its case ID.`,
	"gotestwaf": `GoTestWAF test cases, one case for each payload, encoder and placeholder. "legit"
is a case of a test set whose name holds "false", the tool's false-positive checks;
every other case is "attack".`,
	"generated-legit": `Legitimate and near-miss requests generated by this repository's generator from a
seed. None of it is recorded traffic.`,
}

// awkward are the categories of the generated set that are over-represented on
// purpose.
var awkward = []string{"punctuation-prose", "pasted-code"}

func environmentMarkdown(b *strings.Builder, fields []Field) {
	b.WriteString("## Run environment\n\n")
	header(b, "Item", "Value")
	for _, f := range fields {
		row(b, f.Name, f.Value)
	}
	b.WriteString("\n")
}

func sourcesMarkdown(b *strings.Builder, sources []SourceInfo) {
	b.WriteString("\n## Sources\n\n")
	if len(sources) == 0 {
		b.WriteString("None recorded.\n")
		return
	}
	header(b, "Source", "Repository", "Commit", "Licence", "Included", "Note")
	for _, s := range sources {
		included := "no"
		if s.Included {
			included = "yes"
		}
		row(b, s.Name, orNotRecorded(s.Repo), orNotRecorded(s.Commit), orNotRecorded(s.License), included, s.Note)
	}
	first := true
	for _, s := range sources {
		note, ok := sourceNotes[s.Name]
		if !s.Included || !ok {
			continue
		}
		if first {
			b.WriteString("\n### What the cases of each source are\n")
			first = false
		}
		// The note is this package's own text.
		fmt.Fprintf(b, "\n**%s.** %s\n", cell(s.Name), note)
	}
}

func (in Input) markdown(b *strings.Builder) {
	b.WriteString("\n## Input\n\n")
	conflictLines, conflictRequests := 0, 0
	for _, c := range in.Conflicts {
		conflictLines, conflictRequests = conflictLines+c.Lines, conflictRequests+c.Requests
	}
	fmt.Fprintf(b, `A case line is one request, as import or remote wrote it. %d case lines were read.
%d distinct requests are counted, identical requests being merged. %d lines (%d requests) are left out because the lines that send the
same request disagree on what to expect. A skipped case is a file, test, stage or
combination of a source that the importer did not turn into a case line.

`, in.Lines, in.Distinct, conflictLines, conflictRequests)
	header(b, "Source", "Case lines", "Attack", "Legit", "Near-miss", "Without a payload",
		"Left out as conflicting", "Skipped by the importer")
	var all SourceInput
	skipped, known := 0, true
	counts := func(name string, s SourceInput, skippedCell string) {
		cells := []string{name}
		for _, v := range []int{s.Lines, s.Attack, s.Legit, s.NearMiss, s.NoPayload, s.Conflicting} {
			cells = append(cells, strconv.Itoa(v))
		}
		row(b, append(cells, skippedCell)...)
	}
	reasons := 0
	for _, s := range in.Sources {
		all.Lines += s.Lines
		all.Attack += s.Attack
		all.Legit += s.Legit
		all.NearMiss += s.NearMiss
		all.NoPayload += s.NoPayload
		all.Conflicting += s.Conflicting
		skippedCell := notRecorded
		if s.Skipped == nil {
			known = false
		} else {
			skipped += *s.Skipped
			skippedCell = strconv.Itoa(*s.Skipped)
		}
		reasons += len(s.SkipReasons)
		counts(s.Source, s, skippedCell)
	}
	total := notRecorded
	if known {
		total = strconv.Itoa(skipped)
	}
	counts("all", all, total)

	if len(in.Conflicts) > 0 {
		b.WriteString("\n### Conflicting requests, left out\n\n")
		header(b, "Sources of the lines", "Requests", "Lines")
		for _, c := range in.Conflicts {
			row(b, strings.Join(c.Sources, ", "), strconv.Itoa(c.Requests), strconv.Itoa(c.Lines))
		}
	}
	if reasons > 0 {
		b.WriteString("\n### Skipped source cases\n\n")
		header(b, "Source", "Reason", "Skipped")
		for _, s := range in.Sources {
			for _, r := range s.SkipReasons {
				row(b, s.Source, r.Reason, strconv.Itoa(r.Count))
			}
		}
	}
}

func (g Generated) markdown(b *strings.Builder) {
	b.WriteString("\n## Generated legitimate traffic\n\n")
	fmt.Fprintf(b, `Seed %d, %d lines (source generated-legit). The generator's material is
%d templates and %d entries in %d word lists. A template is one sentence pattern of
a category. An entry is one string of a word list, which fills a slot of a template
or of another entry. The table counts the templates and entries that went into at
least one line, each once however many lines use it; numbers drawn into a slot are
not counted. An entry that several categories use counts in each of them and once
in the row "all".

`, g.Seed, g.N, g.Templates, g.Entries, g.Lists)
	header(b, "Category", "Lines", "Share of lines", "Near-miss lines", "Templates used", "Entries used")
	line := func(name string, lines, nearMiss, templates, entries int) {
		row(b, name, strconv.Itoa(lines), percent(lines, g.N), strconv.Itoa(nearMiss),
			strconv.Itoa(templates), strconv.Itoa(entries))
	}
	lines, nearMiss, awkwardLines := 0, 0, 0
	for _, c := range g.Categories {
		line(c.Name, c.Lines, c.NearMiss, c.Templates, c.Entries)
		lines, nearMiss = lines+c.Lines, nearMiss+c.NearMiss
		if slices.Contains(awkward, c.Name) {
			awkwardLines += c.Lines
		}
	}
	line("all", lines, nearMiss, g.TemplatesUsed, g.EntriesUsed)
	fmt.Fprintf(b, `
- The lines are combinations of %d templates and %d entries, so %d lines are not
  independent trials: one template or entry that a firewall blocks can account for
  many blocked lines.
- The mix of categories is the generator's fixed schedule, not a measurement of real
  traffic. Awkward text is over-represented on purpose: punctuation-prose and
  pasted-code are %s of the lines. A total false positive rate moves with this mix;
  read the rate of each category.
- A line is legitimate unless its text has the canonical shape of an attack: a script
  element, an on...= event handler attribute, a javascript: URL, a command reading
  /etc/passwd or /etc/shadow, or SQL calling a time-delay function. Such a line is
  near-miss and counted apart. The rule was written after one replay of an earlier
  version of the set had been seen, looks at the text alone and applies to every
  entry of these kinds.
- Text in languages other than English had no native review. Names, addresses, phone
  numbers and e-mail addresses are invented; web hosts are reserved names or localhost
  and IP addresses come from the documentation ranges, so loopback and private IP
  addresses are absent. No public data set of real legitimate traffic is included.
`, g.TemplatesUsed, g.EntriesUsed, g.N, percent(awkwardLines, g.N))
	if len(g.Cores) > 0 {
		g.coresMarkdown(b)
	}
}

func (g Generated) coresMarkdown(b *strings.Builder) {
	entries, used := 0, 0
	for _, c := range g.Cores {
		entries, used = entries+c.Entries, used+c.Used
	}
	fmt.Fprintf(b, `
### Core snippets of pasted code

A core snippet is an entry of a word list that holds the pasted text itself (an error
message, a command, a query, a snippet of code, markup or a template, a path, a log
line and so on), as opposed to the sentences around it. The pasted-code lines hold
%d of the %d entries of %d word lists. The table counts, for each list, its entries,
those in at least one pasted-code line, and the pasted-code lines that hold one; one
line may hold several, from one list or more, so the lines do not add up.

`, used, entries, len(g.Cores))
	header(b, "Word list", "Entries", "Used", "Pasted-code lines")
	for _, c := range g.Cores {
		row(b, c.Name, strconv.Itoa(c.Entries), strconv.Itoa(c.Used), strconv.Itoa(c.Lines))
	}
	row(b, "all", strconv.Itoa(entries), strconv.Itoa(used), "")
}
