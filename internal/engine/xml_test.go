const (
	xmlSQL    = `1' UNION SELECT password FROM users--`
	xmlXXE    = `<!DOCTYPE a [<!ENTITY b SYSTEM "file:///etc/hostname">]><a>&b;</a>`
	xmlScript = `<script>alert(1)</script>`
)

// xmlEngine allows application/xml with the given limits (zero: defaults).
func xmlEngine(t *testing.T, mode model.Mode, lim model.Limits) *Engine {
	t.Helper()
	return newEngine(t, Options{Mode: mode, FailOpen: true, Limits: lim, AllowedContentTypes: []string{"application/xml"}})
}

func wantClean(t *testing.T, d model.Decision) {
	t.Helper()
	if d.Action != model.ActionAllow || len(d.Matches) != 0 {
		t.Fatalf("want allow without matches: %+v", d)
	}
}

func wantRule(t *testing.T, d model.Decision, rules ...string) {
	t.Helper()
	for _, r := range rules {
		if !hasMatch(d, r, "body") {
			t.Fatalf("want %s on body: %+v", r, d)
		}
	}
}

func TestXMLMarkupIsNotAnAttack(t *testing.T) {
	for _, tc := range []struct{ name, body string }{
		{"default namespace", `<order xmlns="urn:example:orders"><sku>A-1</sku><qty>2</qty></order>`},
		{"Atom link", `<?xml version="1.0" encoding="utf-8"?><feed xmlns="http://www.w3.org/2005/Atom">` +
			`<title>Release notes</title><link href="https://example.com/a"/><entry><title>First</title>` +
			`<link rel="alternate" href="https://example.com/a/1"/></entry></feed>`},
		{"RSS channel link", `<rss version="2.0"><channel><title>News</title><link>https://example.com/</link></channel></rss>`},
		{"style as a data element", `<format><style>bold</style><size>12</size></format>`},
		{"SOAP envelope", `<?xml version="1.0"?><soap:Envelope xmlns:soap="http://www.w3.org/2003/05/soap-envelope">` +
			`<soap:Header/><soap:Body><m:GetPrice xmlns:m="urn:example:prices"><m:Item>Apples</m:Item></m:GetPrice>` +
			`</soap:Body></soap:Envelope>`},
		{"stylesheet instruction", `<?xml version="1.0"?><?xml-stylesheet type="text/xsl" href="a.xsl"?><report><n>1</n></report>`},
		{"ISO-8859-1 text", "<?xml version=\"1.0\" encoding=\"ISO-8859-1\"?><name>Ren\xe9e</name>"},
		{"bare document type", `<!DOCTYPE note><note><to>Ana</to></note>`},
		{"declaration with blanks around equals", `<?xml version = "1.0" encoding = 'UTF-8' ?><a>x</a>`},
		{"declaration version 1.1", `<?xml version="1.1"?><a>x</a>`},
		{"XHTML content in a feed", `<entry xmlns="http://www.w3.org/2005/Atom"><content type="xhtml">` +
			`<div xmlns="http://www.w3.org/1999/xhtml"><p>Hello <b>there</b>, see <a href="https://example.com/x">this</a>.</p></div>` +
			`</content></entry>`},
		{"SVG shapes", `<drawing xmlns:s="http://www.w3.org/2000/svg"><s:rect x="1" y="1" width="8" height="8" fill="red"/></drawing>`},
		{"comment", `<a><!-- generated by the export job --><b>1</b></a>`},
		{"Excel application instruction", `<?xml version="1.0"?><?mso-application progid="Excel.Sheet"?><Workbook/>`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			wantClean(t, postBody(xmlEngine(t, model.ModeEnforce, model.Limits{}), "application/xml", tc.body))
			wantClean(t, postBody(xmlEngine(t, model.ModeMonitor, model.Limits{}), "application/xml", tc.body))
		})
	}
}

// Only values are read: an injection in an element name, attribute name or
// namespace declaration is not seen (an accepted miss).
